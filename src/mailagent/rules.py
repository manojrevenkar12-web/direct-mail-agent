"""Suppression rules: one YAML definition compiled to numpy (for the agent) and to SQL (for the warehouse)."""

from __future__ import annotations

from typing import Any

import numpy as np

from mailagent import settings

OPS = {"in", "not_in", "eq", "ne", "lt", "le", "gt", "ge", "is_true"}


def _np(rule: dict[str, Any], col: np.ndarray) -> np.ndarray:
    op, v = rule["op"], rule.get("value")
    if op == "in":
        return np.isin(col, v)
    if op == "not_in":
        return ~np.isin(col, v)
    if op == "eq":
        return col == v
    if op == "ne":
        return col != v
    if op == "lt":
        return col < v
    if op == "le":
        return col <= v
    if op == "gt":
        return col > v
    if op == "ge":
        return col >= v
    if op == "is_true":
        return col.astype(bool)
    raise ValueError(f"unknown op {op}")


def evaluate(universe: dict[str, np.ndarray], rules: list[dict[str, Any]] | None = None) -> np.ndarray:
    """A bitmask per company: bit i set when rule i suppresses it. Zero means mailable."""
    rules = rules or settings.suppressions()
    n = len(next(iter(universe.values())))
    mask = np.zeros(n, dtype=np.int64)
    for i, rule in enumerate(rules):
        if rule["op"] not in OPS:
            raise ValueError(f"unknown op {rule['op']}")
        mask |= _np(rule, universe[rule["field"]]).astype(np.int64) << i
    return mask


def reasons(mask: np.ndarray, rules: list[dict[str, Any]] | None = None) -> dict[str, int]:
    rules = rules or settings.suppressions()
    return {r["id"]: int(((mask >> i) & 1).sum()) for i, r in enumerate(rules)}


def _lit(v: Any) -> str:
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        return repr(v)
    return "'" + str(v).replace("'", "''") + "'"


def sql_predicate(rule: dict[str, Any]) -> str:
    f, op, v = rule["field"], rule["op"], rule.get("value")
    sym = {"eq": "=", "ne": "<>", "lt": "<", "le": "<=", "gt": ">", "ge": ">="}
    if op in ("in", "not_in"):
        neg = "not " if op == "not_in" else ""
        return f"{f} {neg}in ({', '.join(_lit(x) for x in v)})"
    if op == "is_true":
        return f"coalesce({f}, false)"
    return f"{f} {sym[op]} {_lit(v)}"


def sql_model(rules: list[dict[str, Any]] | None = None) -> str:
    """The dbt model that applies the same rules in the warehouse (Snowflake in production, DuckDB in tests)."""
    rules = rules or settings.suppressions()
    bits = "\n    + ".join(f"(case when {sql_predicate(r)} then {1 << i} else 0 end)" for i, r in enumerate(rules))
    return (
        "-- generated by scripts/gen_dbt.py from config/suppressions.yaml; do not edit\n"
        "select\n    company_id,\n    sector,\n"
        f"    {bits}\n    as suppression_mask\n"
        "from {{ ref('stg_companies') }}\n"
    )
